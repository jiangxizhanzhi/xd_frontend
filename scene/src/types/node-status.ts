// 设置透明度
export const setNodeOpacity = (node: any, opacity: any) => {
  node.setAttrs({
    image: { opacity },
    text: { opacity },
  });
};
// 更新节点的状态图标
export const setNodeStatus = (node: any, status: any, container: any) => {
  const currentNodeDOM = container?.querySelectorAll(`.x6-cell.x6-node`);
  if (!currentNodeDOM.length) return;
  for (let i = 0; i < currentNodeDOM.length; i++) {
    if (currentNodeDOM[i].getAttribute('data-cell-id') === node.id) {
      const loading = currentNodeDOM[i].querySelectorAll(`.loading`);
      const error = currentNodeDOM[i].querySelectorAll(`.error`);
      const start = currentNodeDOM[i].querySelectorAll(`.start`);
      if (status === 'loading') {
        setNodeOpacity(node, 0.5);
        loading[0].style.visibility = 'visible';
        loading[0].style.transformOrigin = 'center center';
        loading[0].style.transformBox = 'fill-box';
        start[0].style.visibility = 'hidden';
        start[1].style.visibility = 'hidden';
        // loading[0].style.animation='loading 0.55s steps(150) infinite'
        error[0].style.visibility = 'hidden';
      } else if (status === 'error') {
        setNodeOpacity(node, 0.5);
        loading[0].style.visibility = 'hidden';
        error[0].style.visibility = 'visible';
        start[0].style.visibility = 'hidden';
        start[1].style.visibility = 'hidden';
      } else if (status === 'toBeStarted') {
        start[0].style.visibility = 'visible';
        start[1].style.visibility = 'visible';
        start[0].style.opacity = 1;
        start[1].style.opacity = 1;
      } else if (status === 'shutdown') {
        setNodeOpacity(node, 0.5);
        loading[0].style.visibility = 'hidden';
        error[0].style.visibility = 'hidden';
        start[0].style.visibility = 'hidden';
        start[1].style.visibility = 'hidden';
      } else {
        setNodeOpacity(node, 1);
        loading[0].style.visibility = 'hidden';
        error[0].style.visibility = 'hidden';
        start[0].style.visibility = 'hidden';
        start[1].style.visibility = 'hidden';
        start[0].style.opacity = 0;
        start[1].style.opacity = 0;
      }
      return;
    }
  }
};
