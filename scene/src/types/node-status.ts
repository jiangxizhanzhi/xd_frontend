/**
 * 获取节点状态
 * 0：完成 1：报错 2：加载中
 * @param status
 * @param event event等于0时，添加启动状态
 * @param event_status
 */
export function getNodeStatus(status: any, event: any, event_status: any) {
  if (event === 0) {
    return 'toBeStarted';
  } else if (event === 4 && event_status === 4) {
    return 'shutdown';
  } else {
    switch (status) {
      case 4:
        return 'success';
      case 5:
        return 'error';
      case undefined:
        return 'success';
      default:
        return 'loading';
    }
  }
}

